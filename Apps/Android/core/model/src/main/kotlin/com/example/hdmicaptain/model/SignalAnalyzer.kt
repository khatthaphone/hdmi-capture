package com.example.hdmicaptain.model

import kotlin.math.abs
import kotlin.math.max
import kotlin.math.roundToInt
import kotlin.math.sqrt

/** What the capture card is actually delivering. */
sealed interface SignalContent {
    data object Picture : SignalContent
    /** Uniform black: no HDMI signal, or an HDCP-protected source the card refuses to show. */
    data object Black : SignalContent
    /** Uniform colour, typically a card's own "no signal" screen. RGB 0…255. */
    data class Solid(val red: Int, val green: Int, val blue: Int) : SignalContent

    val isNoSignal: Boolean get() = this != Picture
}

/** Port of CaptureCore's `SignalAnalyzer`: classifies a 160×90 sample grid of Y/Cb/Cr values. */
object SignalAnalyzer {
    const val GRID_WIDTH = 160
    const val GRID_HEIGHT = 90

    data class Stats(
        val meanY: Double,
        val stdY: Double = 0.0,
        val meanCb: Double,
        val meanCr: Double,
        val stdChroma: Double = 0.0,
        /** Max − min over the samples; card-generated screens are perfectly flat. */
        val rangeY: Double = 0.0,
        val rangeChroma: Double = 0.0,
    )

    fun classify(stats: Stats, fullRange: Boolean): SignalContent {
        val blackLevel = if (fullRange) 0.0 else 16.0
        // Real pictures, even dark ones, have texture somewhere; flat frames are generated by the card.
        if (stats.rangeY > 8 || stats.rangeChroma > 8) return SignalContent.Picture
        val neutral = abs(stats.meanCb - 128) < 6 && abs(stats.meanCr - 128) < 6
        if (neutral && stats.meanY < blackLevel + 8) return SignalContent.Black
        val (r, g, b) = toRGB(stats.meanY, stats.meanCb, stats.meanCr, fullRange)
        return SignalContent.Solid(r, g, b)
    }

    /** Stats over parallel sample arrays (values 0…255), as filled by the native sampler. */
    fun stats(y: IntArray, cb: IntArray, cr: IntArray): Stats {
        val sy = Welford().apply { y.forEach { add(it.toDouble()) } }
        val scb = Welford().apply { cb.forEach { add(it.toDouble()) } }
        val scr = Welford().apply { cr.forEach { add(it.toDouble()) } }
        return Stats(sy.mean, sy.std, scb.mean, scr.mean, max(scb.std, scr.std), sy.range, max(scb.range, scr.range))
    }

    fun toRGB(y: Double, cb: Double, cr: Double, fullRange: Boolean): Triple<Int, Int, Int> {
        val yn = if (fullRange) y / 255 else (y - 16) / 219
        val cbn = (cb - 128) / (if (fullRange) 255 else 224)
        val crn = (cr - 128) / (if (fullRange) 255 else 224)
        fun clamp(v: Double) = (v.coerceIn(0.0, 1.0) * 255).roundToInt()
        return Triple(clamp(yn + 1.5748 * crn), clamp(yn - 0.1873 * cbn - 0.4681 * crn), clamp(yn + 1.8556 * cbn))
    }

    private class Welford {
        var count = 0.0
        var mean = 0.0
        var m2 = 0.0
        var low = Double.POSITIVE_INFINITY
        var high = Double.NEGATIVE_INFINITY
        val range get() = if (count > 0) high - low else 0.0
        val std get() = if (count > 1) sqrt(m2 / (count - 1)) else 0.0
        fun add(x: Double) {
            low = minOf(low, x)
            high = maxOf(high, x)
            count += 1
            val d = x - mean
            mean += d / count
            m2 += d * (x - mean)
        }
    }
}

/**
 * Port of `SignalMonitor`'s timing: loss is reported only after it persists, so a black scene cut
 * doesn't flash "no signal"; recovery to a picture is reported immediately.
 */
class SignalDebouncer(private val persistenceSeconds: Double = 1.5) {
    var current: SignalContent = SignalContent.Picture
        private set
    private var candidate: SignalContent = SignalContent.Picture
    private var candidateSince = 0.0

    fun reset() {
        candidate = SignalContent.Picture
        current = SignalContent.Picture
    }

    /** Feeds one classification at [timeSeconds]; returns true when [current] changed. */
    fun observe(content: SignalContent, timeSeconds: Double): Boolean {
        // Treat any "no signal" variant as the same candidate so a flickering card screen still counts.
        if (content.isNoSignal != candidate.isNoSignal) candidateSince = timeSeconds
        candidate = content
        val settled = candidate == SignalContent.Picture || timeSeconds - candidateSince >= persistenceSeconds
        if (settled && candidate.isNoSignal != current.isNoSignal) {
            current = candidate
            return true
        }
        return false
    }
}
