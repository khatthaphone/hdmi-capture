namespace HDMICaptain.Core;

/// <summary>What the capture card is actually delivering.</summary>
public abstract record SignalContent
{
    private SignalContent() { }

    public sealed record Picture : SignalContent;

    /// <summary>Uniform black: no HDMI signal, or an HDCP-protected source the card refuses to show.</summary>
    public sealed record Black : SignalContent;

    /// <summary>Uniform colour, typically a card's own "no signal" screen. RGB 0..255.</summary>
    public sealed record Solid(int Red, int Green, int Blue) : SignalContent;

    public bool IsNoSignal => this is not Picture;
}

/// <summary>
/// Port of CaptureCore's SignalAnalyzer: classifies a 160x90 sample grid of Y/Cb/Cr values.
/// Shared fixture: docs/fixtures/signal-classify.json.
/// </summary>
public static class SignalAnalyzer
{
    public const int GridWidth = 160;
    public const int GridHeight = 90;

    /// <param name="RangeY">Max minus min over the samples; card-generated screens are perfectly flat.</param>
    public readonly record struct Stats(
        double MeanY,
        double StdY,
        double MeanCb,
        double MeanCr,
        double StdChroma,
        double RangeY,
        double RangeChroma);

    public static SignalContent Classify(Stats stats, bool fullRange)
    {
        var blackLevel = fullRange ? 0.0 : 16.0;
        // Real pictures, even dark ones, have texture somewhere; flat frames are generated by the card.
        if (stats.RangeY > 8 || stats.RangeChroma > 8) return new SignalContent.Picture();
        var neutral = Math.Abs(stats.MeanCb - 128) < 6 && Math.Abs(stats.MeanCr - 128) < 6;
        if (neutral && stats.MeanY < blackLevel + 8) return new SignalContent.Black();
        var (r, g, b) = ToRgb(stats.MeanY, stats.MeanCb, stats.MeanCr, fullRange);
        return new SignalContent.Solid(r, g, b);
    }

    /// <summary>Stats over parallel sample arrays (values 0..255), as filled by the native sampler.</summary>
    public static Stats ComputeStats(ReadOnlySpan<int> y, ReadOnlySpan<int> cb, ReadOnlySpan<int> cr)
    {
        var sy = new Welford();
        foreach (var v in y) sy.Add(v);
        var scb = new Welford();
        foreach (var v in cb) scb.Add(v);
        var scr = new Welford();
        foreach (var v in cr) scr.Add(v);
        return new Stats(sy.Mean, sy.Std, scb.Mean, scr.Mean, Math.Max(scb.Std, scr.Std), sy.Range, Math.Max(scb.Range, scr.Range));
    }

    public static (int R, int G, int B) ToRgb(double y, double cb, double cr, bool fullRange)
    {
        var yn = fullRange ? y / 255 : (y - 16) / 219;
        var cbn = (cb - 128) / (fullRange ? 255 : 224);
        var crn = (cr - 128) / (fullRange ? 255 : 224);
        static int Clamp(double v) => (int)Math.Round(Math.Clamp(v, 0.0, 1.0) * 255, MidpointRounding.AwayFromZero);
        return (Clamp(yn + 1.5748 * crn), Clamp(yn - 0.1873 * cbn - 0.4681 * crn), Clamp(yn + 1.8556 * cbn));
    }

    private sealed class Welford
    {
        private double _count;
        private double _m2;
        private double _low = double.PositiveInfinity;
        private double _high = double.NegativeInfinity;

        public double Mean { get; private set; }
        public double Range => _count > 0 ? _high - _low : 0.0;
        public double Std => _count > 1 ? Math.Sqrt(_m2 / (_count - 1)) : 0.0;

        public void Add(double x)
        {
            _low = Math.Min(_low, x);
            _high = Math.Max(_high, x);
            _count += 1;
            var d = x - Mean;
            Mean += d / _count;
            _m2 += d * (x - Mean);
        }
    }
}

/// <summary>
/// Port of SignalMonitor's timing (Kotlin SignalDebouncer): loss is reported only after it persists, so a
/// black scene cut doesn't flash "no signal"; recovery to a picture is reported immediately.
/// Shared fixture: docs/fixtures/signal-monitor.json.
/// </summary>
public sealed class SignalDebouncer(double persistenceSeconds = 1.5)
{
    private SignalContent _candidate = new SignalContent.Picture();
    private double _candidateSince;

    public SignalContent Current { get; private set; } = new SignalContent.Picture();

    public void Reset()
    {
        _candidate = new SignalContent.Picture();
        Current = new SignalContent.Picture();
    }

    /// <summary>Feeds one classification at <paramref name="timeSeconds"/>; returns true when <see cref="Current"/> changed.</summary>
    public bool Observe(SignalContent content, double timeSeconds)
    {
        // Treat any "no signal" variant as the same candidate so a flickering card screen still counts.
        if (content.IsNoSignal != _candidate.IsNoSignal) _candidateSince = timeSeconds;
        _candidate = content;
        var settled = _candidate is SignalContent.Picture || timeSeconds - _candidateSince >= persistenceSeconds;
        if (settled && _candidate.IsNoSignal != Current.IsNoSignal)
        {
            Current = _candidate;
            return true;
        }
        return false;
    }
}
