import CoreMedia
import CoreVideo
import Foundation
import QuartzCore

/// What the capture card is actually delivering.
public enum SignalContent: Equatable, Sendable {
    case picture
    /// Uniform black: no HDMI signal, or an HDCP-protected source the card refuses to show.
    case black
    /// Uniform colour, typically a card's own "no signal" screen. RGB 0…255.
    case solid(red: Int, green: Int, blue: Int)

    public var isNoSignal: Bool { self != .picture }
}

/// Pure frame classifier over a sparse sample grid (64×36), cheap enough to run on the capture queue.
public enum SignalAnalyzer {
    public static let gridWidth = 64
    public static let gridHeight = 36

    public struct Stats: Equatable, Sendable {
        public var meanY: Double
        public var stdY: Double
        public var meanCb: Double
        public var meanCr: Double
        public var stdChroma: Double
    }

    public static func classify(_ stats: Stats, fullRange: Bool) -> SignalContent {
        let blackLevel = fullRange ? 0.0 : 16.0
        // Real pictures, even dark ones, have texture; flat frames are generated by the card.
        guard stats.stdY < 2.5, stats.stdChroma < 2.5 else { return .picture }
        let neutral = abs(stats.meanCb - 128) < 6 && abs(stats.meanCr - 128) < 6
        if neutral, stats.meanY < blackLevel + 8 { return .black }
        let rgb = toRGB(y: stats.meanY, cb: stats.meanCb, cr: stats.meanCr, fullRange: fullRange)
        return .solid(red: rgb.0, green: rgb.1, blue: rgb.2)
    }

    /// Samples a bi-planar 4:2:0 buffer (420v / 420f). Returns nil for other formats.
    public static func stats(of buffer: CVPixelBuffer) -> Stats? {
        let format = CVPixelBufferGetPixelFormatType(buffer)
        guard format == kCVPixelFormatType_420YpCbCr8BiPlanarVideoRange || format == kCVPixelFormatType_420YpCbCr8BiPlanarFullRange,
              CVPixelBufferGetPlaneCount(buffer) == 2
        else { return nil }
        CVPixelBufferLockBaseAddress(buffer, .readOnly)
        defer { CVPixelBufferUnlockBaseAddress(buffer, .readOnly) }
        guard let yBase = CVPixelBufferGetBaseAddressOfPlane(buffer, 0)?.assumingMemoryBound(to: UInt8.self),
              let cBase = CVPixelBufferGetBaseAddressOfPlane(buffer, 1)?.assumingMemoryBound(to: UInt8.self)
        else { return nil }
        let width = CVPixelBufferGetWidthOfPlane(buffer, 0)
        let height = CVPixelBufferGetHeightOfPlane(buffer, 0)
        let yStride = CVPixelBufferGetBytesPerRowOfPlane(buffer, 0)
        let cStride = CVPixelBufferGetBytesPerRowOfPlane(buffer, 1)
        guard width >= 2, height >= 2 else { return nil }

        var y = Welford(), cb = Welford(), cr = Welford()
        for gy in 0..<gridHeight {
            let py = (gy * 2 + 1) * height / (gridHeight * 2)
            for gx in 0..<gridWidth {
                let px = (gx * 2 + 1) * width / (gridWidth * 2)
                y.add(Double(yBase[py * yStride + px]))
                let c = (py / 2) * cStride + (px / 2) * 2
                cb.add(Double(cBase[c]))
                cr.add(Double(cBase[c + 1]))
            }
        }
        return Stats(meanY: y.mean, stdY: y.std, meanCb: cb.mean, meanCr: cr.mean, stdChroma: max(cb.std, cr.std))
    }

    static func toRGB(y: Double, cb: Double, cr: Double, fullRange: Bool) -> (Int, Int, Int) {
        let yn = fullRange ? y / 255 : (y - 16) / 219
        let cbn = (cb - 128) / (fullRange ? 255 : 224)
        let crn = (cr - 128) / (fullRange ? 255 : 224)
        let r = yn + 1.5748 * crn
        let g = yn - 0.1873 * cbn - 0.4681 * crn
        let b = yn + 1.8556 * cbn
        func clamp(_ v: Double) -> Int { Int((max(0, min(1, v)) * 255).rounded()) }
        return (clamp(r), clamp(g), clamp(b))
    }

    private struct Welford {
        var count = 0.0, mean = 0.0, m2 = 0.0
        mutating func add(_ x: Double) {
            count += 1
            let d = x - mean
            mean += d / count
            m2 += d * (x - mean)
        }
        var std: Double { count > 1 ? (m2 / (count - 1)).squareRoot() : 0 }
    }
}

/// Frame sink that classifies every Nth frame and reports changes after they persist,
/// so a black scene cut doesn't flash a "no signal" message.
public final class SignalMonitor: FrameSink, @unchecked Sendable {
    /// Called on the main queue.
    public var onChange: ((SignalContent) -> Void)?

    private let every: Int
    private let persistence: CFTimeInterval
    private let lock = NSLock()
    private var counter = 0
    private var reported: SignalContent = .picture
    private var candidate: SignalContent = .picture
    private var candidateSince: CFTimeInterval = 0

    public init(every: Int = 10, persistence: CFTimeInterval = 1.5) {
        self.every = every
        self.persistence = persistence
    }

    public var current: SignalContent {
        lock.withLock { reported }
    }

    public func reset() {
        lock.withLock {
            counter = 0
            candidate = .picture
            if reported != .picture {
                reported = .picture
                notify(.picture)
            }
        }
    }

    public func consume(_ sampleBuffer: CMSampleBuffer) {
        guard let buffer = CMSampleBufferGetImageBuffer(sampleBuffer) else { return }
        let due = lock.withLock {
            counter += 1
            return counter % every == 0
        }
        guard due, let stats = SignalAnalyzer.stats(of: buffer) else { return }
        let fullRange = CVPixelBufferGetPixelFormatType(buffer) == kCVPixelFormatType_420YpCbCr8BiPlanarFullRange
        observe(SignalAnalyzer.classify(stats, fullRange: fullRange), at: CACurrentMediaTime())
    }

    /// Visible for tests: feeds a classification at a given time.
    func observe(_ content: SignalContent, at time: CFTimeInterval) {
        lock.withLock {
            // Treat any "no signal" variant as the same candidate so a flickering card screen still counts.
            if content.isNoSignal != candidate.isNoSignal || (content == .picture) != (candidate == .picture) {
                candidate = content
                candidateSince = time
            } else {
                candidate = content
            }
            // Recovery to a picture is reported immediately; loss only after it persists.
            let settled = candidate == .picture || time - candidateSince >= persistence
            if settled, candidate.isNoSignal != reported.isNoSignal {
                reported = candidate
                notify(candidate)
            }
        }
    }

    private func notify(_ content: SignalContent) {
        DispatchQueue.main.async { [weak self] in self?.onChange?(content) }
    }
}
